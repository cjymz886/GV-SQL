"""Use SQL retrieval to obtain database schema information and reduce information redundancy. The retrieval strategy is as follows:
	1. Use the LLM to extract keywords from the query, then recall based on the keywords using BM25
	2. Use the trained qwen-embedding and qwen-ranker for recall
	3. The final result is a fusion of the two approaches
"""

import os
import sys
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import json
import random
import torch
from transformers import AutoTokenizer, AutoModel,AutoModelForCausalLM
import nltk
nltk.data.path.append('./nltk_data')
from nltk.tokenize import word_tokenize
from nltk.corpus import stopwords
from nltk.stem import PorterStemmer
from rank_bm25 import BM25Okapi
import faiss
import pickle
from sentence_transformers import SentenceTransformer
import numpy as np
import logging
from utils.my_logger import setup_logging


setup_logging(log_level=logging.INFO, log_file='gv_sql.log')
logger = logging.getLogger(__name__)


os.environ["CUDA_VISIBLE_DEVICES"] = "6,7"



class  SQLRecllModule():
	def __init__(self,mode='train',topk=30, use_stemming=True, remove_stopwords=True):
		self.device = torch.device('cuda:1')

		self.query_keywords_file = f"./data/BIRD/{mode}/{mode}_sql_keywords.json"
		self.sql_enrich_file = f"./data/BIRD/{mode}/{mode}_enhanced_column.json"
		self.db_ddl_file = f'./data/BIRD/{mode}/{mode}_ddl_schema.json'

		# If a database has fewer columns than max_col_num, skip retrieval and directly recall all columns
		self.max_col_num = topk  
		self.load_ddl_schema()
		self.load_keywords()

		#bm25
		self.stemmer = PorterStemmer() if use_stemming else None
		self.stop_words = set(stopwords.words('english')) if remove_stopwords else set()
		self.bm25_topk = 100
		self.create_bm25_index()

		#embedding &ranker
		self.recall_topk= 100
		self.recall_threshold = 0.0
		self.ranker_topk = topk  #fina topk
		self.ranker_threshold = 0.0
		self.column_index_path = f'./data/BIRD/database/{mode}_column_index.faiss'
		self.column_metadata_path = f'./data/BIRD/database/{mode}_column_metadata.pkl'
		self.recall_model_path = "./models/recall_model/checkpoint-570"
		self.ranker_model_path = "./models/ranker_model/checkpoint-285"
		self.load_recall_model()
		self.load_ranker_model()
		self.load_column_recall_index()


	def load_keywords(self):
		"""load keywords of question and evidence"""
		with open(self.query_keywords_file,'r',encoding='utf-8') as f:
			kdata = json.load(f)

		self.kw_map = {}
		for item in kdata:
			question = item['question']
			evidence = item['evidence']
			kw = item['keywords']
			key = question + '|' + evidence
			self.kw_map[key] = kw

	def load_recall_model(self):
		"""Load the fine-tuned embed model"""
		self.recall_model = SentenceTransformer(
			self.recall_model_path,
			device=torch.device('cuda:6'),
			model_kwargs={"attn_implementation": "flash_attention_2"},
			processor_kwargs={"padding_side": "left"}
		)

	def load_ranker_model(self):
		"""Load the ranker model, using the qwen3-reranker-8b fine-tuned model"""
		self.ranker_tokenizer = AutoTokenizer.from_pretrained(self.ranker_model_path, padding_side='left')
		self.ranker_model = AutoModelForCausalLM.from_pretrained(self.ranker_model_path,
													 dtype=torch.float16,
													 attn_implementation="flash_attention_2",
													 device_map=torch.device('cuda:7'))
													 
	def load_column_recall_index(self):
		"""Load the database column name vector index"""
		self.column_index = faiss.read_index(self.column_index_path)
		with open(self.column_metadata_path, "rb") as f:
			column_metadata = pickle.load(f)
		self.column_list = column_metadata['sentences']
		logger.info("Loaded the enhanced column vector index")

	def load_ddl_schema(self):
		"""Load the database DDL schema information, which is generated by running create_ddl_schema.py"""
		with open(self.db_ddl_file,'r',encoding='utf-8') as f:
			self.ddl_schema = json.load(f)
		
		# Count how many tables and columns each database has. The main purpose is that for simple databases, recall all columns directly without going through the retrieval path
		self.ddl_schema_count = {}
		self.column_info = {}
		for db_id in self.ddl_schema:
			tables = self.ddl_schema[db_id]
			col_num = 0
			for table in tables:
				columns = self.ddl_schema[db_id][table]
				col_num += len(columns)
				for column in tables[table]['column_value']:
					key = db_id+'|'+table +'|' + column
					self.column_info[key] = tables[table]['column_value'][column]
			self.ddl_schema_count[db_id] ={'table_num':len(tables),'column_num':col_num}
		logger.info("Loaded DDL schema information")

	def _tokenize(self, text):
		"""Tokenize before BM25 recall"""
		tokens = word_tokenize(text.lower())
		tokens = [t for t in tokens if t.isalnum()]
		if self.stop_words:
			tokens = [t for t in tokens if t not in self.stop_words]
		if self.stemmer:
			tokens = [self.stemmer.stem(t) for t in tokens]
		return tokens

	def create_bm25_index(self):
		"""Build the BM25 index, one for each database"""
		with open(self.sql_enrich_file,'r',encoding='utf-8') as f:
			self.db_enrich_dict = json.load(f)

		self.doc_dict = {}
		for key in self.column_info:
			db_id = key.split('|')[0].strip()
			enrich_info = self.db_enrich_dict.get(key,'')
			samples = self.column_info[key]['sample_values']
			doc = key + '$$' + str(samples) + ' ' + enrich_info
			if db_id not in self.doc_dict:
				self.doc_dict[db_id] = [doc]
			else:
				self.doc_dict[db_id].append(doc)
		self.bm25 = {}
		for key in self.doc_dict:
			tokenized_corpus = [self._tokenize(doc) for doc in self.doc_dict[key]]
			self.bm25[key] = BM25Okapi(tokenized_corpus, k1=1.2, b=0.75)

	def bm25_search(self, query,db_id):
		"""Recall and retrieve using the BM25 method"""
		tokenized_query = self._tokenize(query.lower())
		recall_res = []
		for doc in self.bm25[db_id].get_top_n(tokenized_query, self.doc_dict[db_id], n=self.bm25_topk):
			key = doc.split('$$')[0].strip()
			recall_res.append(key)
		return recall_res

	def get_recall_embed(self, query):
		"""Use the recall model to obtain the query embedding, then use vector search to retrieve the related columns"""
		with torch.no_grad():
			query_embeddings = self.recall_model.encode([query], prompt_name='query')
			norms = np.linalg.norm(query_embeddings, axis=1, keepdims=True)
			return query_embeddings / norms

	def embed_search(self,query,db_id):
		"""Use the recall model to recall the related database information"""
		vector = self.get_recall_embed(query)
		scores, indices = self.column_index.search(vector.astype(np.float32), self.recall_topk)
		res = []
		for idx, score in zip(indices[0], scores[0]):
			if  idx >= len(self.column_list):
				continue
			if score > self.recall_threshold:
				key = self.column_list[idx]
				key_split = key.strip().split('|')
				assert len(key_split)==3
				if key_split[0]!=db_id:
					continue
				res.append(key)
		return res

	def predict_ranker_batch(self,query,doc_list):
		"""Request the recall model in batch mode to improve inference speed"""

		token_false_id = self.ranker_tokenizer.convert_tokens_to_ids("no")
		token_true_id = self.ranker_tokenizer.convert_tokens_to_ids("yes")
		max_length = 8192

		def format_instruction(query, doc):
			instruction = 'Given sql query, retrieve relevant columns that answer the query'
			output = "<Instruct>: {instruction}\n<Query>: {query}\n<Document>: {doc}".format(instruction=instruction,
																							 query=query, doc=doc)
			return output

		def process_inputs(pairs):

			prefix = "<|im_start|>system\nJudge whether the Document meets the requirements based on the Query and the Instruct provided. Note that the answer can only be \"yes\" or \"no\".<|im_end|>\n<|im_start|>user\n"
			suffix = "<|im_end|>\n<|im_start|>assistant\n<think>\n\n</think>\n\n"
			prefix_tokens = self.ranker_tokenizer.encode(prefix, add_special_tokens=False)
			suffix_tokens = self.ranker_tokenizer.encode(suffix, add_special_tokens=False)

			inputs = self.ranker_tokenizer(
				pairs, padding=False, truncation='longest_first',
				return_attention_mask=False, max_length=max_length - len(prefix_tokens) - len(suffix_tokens)
			)
			for i, ele in enumerate(inputs['input_ids']):
				inputs['input_ids'][i] = prefix_tokens + ele + suffix_tokens
			inputs = self.ranker_tokenizer.pad(inputs, padding=True, return_tensors="pt", max_length=max_length)
			for key in inputs:
				inputs[key] = inputs[key].to(self.ranker_model.device)
			return inputs

		@torch.no_grad()
		def compute_logits(inputs, **kwargs):
			batch_scores = self.ranker_model(**inputs).logits[:, -1, :]
			true_vector = batch_scores[:, token_true_id]
			false_vector = batch_scores[:, token_false_id]
			batch_scores = torch.stack([false_vector, true_vector], dim=1)
			batch_scores = torch.nn.functional.log_softmax(batch_scores, dim=1)
			scores = batch_scores[:, 1].exp().tolist()
			return scores

		pairs = [format_instruction(query, doc) for doc in doc_list]
		inputs = process_inputs(pairs)
		scores = compute_logits(inputs)
		return scores

	def ranker_result(self,query,recall_res,bs=8):
		"""Rank the recalled results"""
		doc_list = []
		for doc in recall_res:
			meaning = self.db_enrich_dict.get(doc, '')
			if meaning:
				doc = doc + ':' + meaning
			doc_list.append(doc)

		batch = []
		fres = []
		k = 0
		for doc in doc_list:
			batch.append(doc)
			if len(batch) == bs:
				res = self.predict_ranker_batch(query, batch)
				for _, sim in enumerate(res):
					key = recall_res[k]
					fres.append([key, sim])
					k += 1
				batch = []

		if batch:
			res = self.predict_ranker_batch(query, batch)
			for _, sim in enumerate(res):
				key = recall_res[k]
				fres.append([key, sim])
				k += 1
		return fres

	def output_format(self,db_id,recall_res,mode='full'):
		"""Merge the recalled schema information into a data structure, convenient for later conversion to markdown"""
		fres = {}
		for table in self.ddl_schema[db_id]:
			p_keys = self.ddl_schema[db_id][table]['primary_keys']
			f_keys = [f['constraint'] for f in self.ddl_schema[db_id][table]['foreign_keys']]

			full_col_list = []
			recall_col_list = []

			for column in self.ddl_schema[db_id][table]['column_value']:
				key = db_id + '|' + table + '|' + column
				description = self.db_enrich_dict.get(key,'')
				col_type = self.ddl_schema[db_id][table]['column_value'][column]['data_type']
				samples = self.ddl_schema[db_id][table]['column_value'][column]['sample_values']
				if key in recall_res:
					recall_col_list.append({'name':column,'type':col_type,'description':description,'samples':samples})
				full_col_list.append({'name':column,'type':col_type,'description':description,'samples':samples})

			if mode=='full':
				fres[table] = {}
				fres[table]['column_value'] = full_col_list
				fres[table]['primary_keys'] = p_keys
				fres[table]['foreign_keys'] = f_keys
			else:
				if recall_col_list:
					fres[table] = {}
					fres[table]['column_value'] = recall_col_list
					fres[table]['primary_keys'] = p_keys
					fres[table]['foreign_keys'] = f_keys
		return fres


	def convet_md_format(self,fres):
		"""
		Convert the recalled schema information to markdown format
		"""
		text = ""
		for table in fres:
			text += "# Table: " + table  + '\n'
			text += "# Column information: " +'\n'
			headers = ['column_name', 'column_type', 'column_description', 'value_examples']
			header_row = "| " + " | ".join(headers) + " |"
			separator = "| " + " | ".join(["---"] * len(headers)) + " |"
			rows = []
			for column in fres[table]['column_value']:
				column_name = column["name"]
				column_type = column["type"]
				column_description = column["description"]
				value_examples = column["samples"]
				# Randomly shuffle the specific value list of the column, control the length, and take the top 5
				random.shuffle(value_examples)
				row = [column_name, column_type, column_description, str(value_examples[:5])]
				rows.append("| " + " | ".join(row) + " |")
			markdown_content = "\n".join([header_row, separator] + rows)
			text += markdown_content + '\n'

			p_keys = fres[table]['primary_keys']
			f_keys = fres[table]['foreign_keys']
			text += "# Primary keys : " + ', '.join(p_keys) + '\n'
			text += '# Foreign keys: ' + ', '.join(f_keys) + '\n\n'
		return text

	def get_retrieve_result(self,item):
		"""Main module for recalling the database information related to the query"""
		db_id = item['db_id']
		if self.ddl_schema_count[db_id]['column_num'] > self.max_col_num:
			query = item['question']
			evidence = item['evidence']
			keywords = self.kw_map.get(query+'|'+evidence,[])
			kw_list = list(set(keywords + query.split(' ') + evidence.split(' ')))


			#bm25 recall
			bm25_recall_res = self.bm25_search(' '.join(kw_list),db_id)
			# logger.info(f"bm25_recall:{bm25_recall_res}\n")

			#embed recall
			embed_recall_res1 = self.embed_search(query,db_id)
			embed_recall_res2 = self.embed_search(evidence, db_id)
			embed_recall_res = list(set(embed_recall_res1+embed_recall_res2))
			# logger.info(f"embed_recall: {embed_recall_res}\n")

			#ranker recall result
			merge_recall_res = list(set(bm25_recall_res + embed_recall_res))
			rank_recall_res = self.ranker_result(query + ' ' + evidence,merge_recall_res)
			rank_recall_res = sorted(rank_recall_res, key=lambda x: x[1], reverse=True)
			rank_recall_res = [r[0] for r in rank_recall_res[:self.ranker_topk] if r[1]> self.ranker_threshold]
			# logger.info(f"ranker_res: {rank_recall_res}")
			fres = self.output_format(db_id,rank_recall_res,'recall')
			schema_content = self.convet_md_format(fres)
		else:
			logger.info(f"{db_id}: data has {self.ddl_schema_count[db_id]['column_num']} columns in total, which is less than the set threshold, so the overall schema is used directly")
			fres = self.output_format(db_id, [], 'full')
			schema_content = self.convet_md_format(fres)
		return schema_content


